package io.github.zazalng.prickcal.global.entities;

import group.worldstandard.pudel.api.database.Column;
import group.worldstandard.pudel.api.database.Entity;

/**
 * Represents a template user entity associated with an account.
 */
@Entity(tableName = "template_user")
public class TemplateUser {
    /**
     * Key record column require by API
     */
    @Column
    private Long id;
    /**
     * Belongs to {@link Account}.id
     */
    @Column(unique = true)
    private long uid;
    /**
     * The type of the template user.
     */
    @Column(unique = true)
    private String type;
    /**
     * The URL associated with the template user.
     */
    @Column
    private String messageId;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public long getUid() {
        return uid;
    }

    public void setUid(long uid) {
        this.uid = uid;
    }

    public String getType() {
        return type;
    }

    public void setType(String type) {
        this.type = type;
    }

    public String getMessageId() {
        return messageId;
    }

    public void setMessageId(String messageId) {
        this.messageId = messageId;
    }
}
